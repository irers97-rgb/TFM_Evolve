def read_ccaa_indexed_sheet(path, sheet, header_row_idx, name_col, value_cols):
    rows = _wb_rows(path, sheet)
    out = {}
    for r in rows[header_row_idx:]:
        ccaa = normalize_ccaa(r[name_col])
        if ccaa is None:
            continue
        out.setdefault(ccaa, {})
        for var, col in value_cols.items():
            out[ccaa][var] = r[col]
    return out

