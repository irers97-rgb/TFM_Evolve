CHAPTER_NAMES = {
    "0100": "Enfermedades infecciosas y parasitarias", "0200": "Neoplasias",
    "0300": "Enf. sangre / sist. inmunitario", "0400": "Enf. endocrinas, nutricionales y metabólicas",
    "0500": "Trastornos mentales", "0600": "Enf. sistema nervioso", "0700": "Enf. del ojo",
    "0800": "Enf. del oído", "0900": "Enf. sistema circulatorio", "1000": "Enf. sistema respiratorio",
    "1100": "Enf. aparato digestivo", "1200": "Enf. piel y tejido subcutáneo",
    "1300": "Enf. sistema osteomuscular", "1400": "Enf. sistema genitourinario",
    "1500": "Complicaciones embarazo/parto", "1600": "Enf. período perinatal",
    "1700": "Anomalías congénitas", "1800": "Síntomas y signos anormales",
    "1900": "Lesiones y envenenamientos", "2100": "Factores que influyen en el estado de salud",
}

def chapter_rows(rows, start, end, code_col=0):
    """Filas de nivel capítulo (código de 4 dígitos terminado en '00')."""
    out = {}
    for r in rows[start:end]:
        label = r[code_col]
        if not label or not isinstance(label, str):
            continue
        m = re.match(r"^\s*(\d{4})\s+(.*)", label.strip())
        if not m:
            continue
        code, name = m.groups()
        if code.endswith("00") and code != "0000":
            out[code] = (name.strip(), r)
    return out

def _wb_rows(path, sheet):
    wb = openpyxl.load_workbook(DATA_DIR / path, read_only=True, data_only=True)
    return list(wb[sheet].iter_rows(values_only=True))

"""## 3.2 Limpieza: tipado, valores ".." y nulos, normalización de CCAA, snake_case

- **Cabeceras variables por hoja**: se localiza dinámicamente la fila de cabecera de cada hoja de `Tablas_CCAA_2023.xlsx` (de la 3 a la 7 según la tabla).
- **Nombres de CCAA no homogéneos entre ficheros**: `normalize_ccaa()` quita tildes, comas y la `ñ` (**imprescindible**: sin sustituir `ñ→n`, País Vasco y Cataluña no casan con el diccionario canónico) y hace *match* por prefijo.
- **Ceuta y Melilla**: columnas separadas en `Alta_Diagnostico_Provincia`, fila combinada en `Tablas_CCAA_2023` → se agregan como una única unidad territorial en toda la capa gold.
- **Valores `..` (secreto estadístico)**: se tratan como ausentes, nunca como cero.
"""

CCAA_CANON = {
    "andalucia": "Andalucía", "aragon": "Aragón", "asturias": "Asturias, Principado de",
    "balears": "Balears, Illes", "canarias": "Canarias", "cantabria": "Cantabria",
    "castilla y leon": "Castilla y León", "castilla - la mancha": "Castilla - La Mancha",
    "castilla la mancha": "Castilla - La Mancha", "cataluna": "Cataluña",
    "comunitat valenciana": "Comunitat Valenciana", "extremadura": "Extremadura",
    "galicia": "Galicia", "madrid": "Madrid, Comunidad de", "murcia": "Murcia, Región de",
    "navarra": "Navarra, Comunidad Foral de", "pais vasco": "País Vasco", "rioja": "Rioja, La",
    "ceuta y melilla": "Ceuta y Melilla", "ceuta": "Ceuta y Melilla",
}

def normalize_ccaa(raw):
    if not raw or not isinstance(raw, str):
        return None
    s = raw.lower().strip()
    s = (s.replace("á","a").replace("é","e").replace("í","i").replace("ó","o").replace("ú","u")
           .replace("ñ","n").replace(",", "").replace(".", ""))
    s = re.sub(r"\s+", " ", s)
    for key in CCAA_CANON:
        if s.startswith(key):
            return CCAA_CANON[key]
    return None

"""## 3.3 Integración: `Alta_Diagnostico_Provincia` (diagnóstico × CCAA) con `Tablas_CCAA_2023` (dotación/personal/urgencias × CCAA)"""

def load_altas_diagnostico_provincia():
    rows = _wb_rows("Alta_Diagnostico_Provincia.xlsx", "tabla-74901")
    start = end = None
    for i, r in enumerate(rows):
        if r[0] == "Ambos sexos":
            start = i + 1
        elif r[0] == "Hombres" and start is not None:
            end = i; break
    chap = chapter_rows(rows, start, end)

    ccaa_cols = {
        2:"Andalucía", 11:"Aragón", 15:"Asturias, Principado de", 16:"Balears, Illes",
        17:"Canarias", 20:"Cantabria", 21:"Castilla y León", 31:"Castilla - La Mancha",
        37:"Cataluña", 42:"Comunitat Valenciana", 46:"Extremadura", 49:"Galicia",
        54:"Madrid, Comunidad de", 55:"Murcia, Región de", 56:"Navarra, Comunidad Foral de",
        57:"País Vasco", 61:"Rioja, La",
    }
    recs = []
    for code, (name, r) in chap.items():
        for col, ccaa in ccaa_cols.items():
            recs.append({"patologia_cie10": code, "patologia_nombre": CHAPTER_NAMES.get(code, name),
                         "ccaa": ccaa, "altas": r[col]})
        ceuta, melilla = (r[62] or 0), (r[63] or 0)
        recs.append({"patologia_cie10": code, "patologia_nombre": CHAPTER_NAMES.get(code, name),
                     "ccaa": "Ceuta y Melilla", "altas": ceuta + melilla})
    return pd.DataFrame(recs)

